import {build} from 'esbuild';
import {createElement as h} from 'react';
import {create,act} from 'react-test-renderer';
import assert from 'node:assert/strict';
await build({entryPoints:['../sales-app/src/routes/index.tsx'],outfile:'.runtime/store-component.mjs',bundle:true,platform:'node',format:'esm',jsx:'automatic',packages:'external',plugins:[{name:'route',setup(b){b.onResolve({filter:/^@tanstack\/react-router$/},()=>({path:'router',namespace:'local'}));b.onLoad({filter:/.*/,namespace:'local'},()=>({contents:'export const createFileRoute=()=>options=>options;',loader:'js'}));}}]});
const {Route}=await import('../.runtime/store-component.mjs');
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
globalThis.window={location:{search:''},scrollTo(){}};
globalThis.document={getElementById(){return {scrollIntoView(){}};}};
const realFetch=globalThis.fetch;globalThis.fetch=(url,opts)=>realFetch(new URL(url,'http://localhost:5173'),opts);
let app;await act(async()=>{app=create(h(Route.component));});
await act(async()=>{await new Promise(r=>setTimeout(r,150));});
assert.equal(app.root.findAllByProps({className:'match'}).length,4);
const explore=app.root.findAllByType('button').find(b=>b.children.includes('Explore stadium'));
await act(()=>explore.props.onClick());
assert.equal(app.root.findAllByProps({className:'stadium-stand-cards'}).length,1);
const cards=app.root.findByProps({className:'stadium-stand-cards'}).findAllByType('button');
await act(()=>cards[1].props.onClick());
const checkout=app.root.findByType('aside');
assert.ok(checkout.findAllByType('b').some(b=>b.children.includes('Pavilion')));
assert.ok(checkout.findByProps({className:'total'}).findByType('b').children.join('').includes('3,150'));
await act(()=>checkout.findByProps({'aria-label':'Ticket quantity'}).props.onChange({target:{value:'2'}}));
assert.ok(checkout.findByProps({className:'total'}).findByType('b').children.join('').includes('6,300'));
assert.ok(app.root.findByProps({className:'stadium-model'}).props['aria-label'].includes('Pavilion'));
await act(()=>app.unmount());globalThis.fetch=realFetch;
console.log('PASS actual storefront catalogue → stadium → Pavilion selection → quantity → synchronized checkout total');
